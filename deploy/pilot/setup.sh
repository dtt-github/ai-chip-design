#!/usr/bin/env bash
# One-time setup for the pilot host. Safe to re-run: existing secrets are kept.
#   1. creates .env with fresh secrets (you fill in WAFER_DOMAIN, ACME_EMAIL, ADMIN_EMAIL, the AI key)
#   2. writes the production sign-in config (rauthy/config.toml, rauthy/bootstrap/clients.json)
#   3. creates the data and backup directories, owned by the API's user (uid 10001)
#   4. pulls the LibreLane image and installs the PDK into the wafersmith_pdk volume
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd ../.. && pwd)"

rand() { head -c "$1" /dev/urandom | base64 | tr -d '/+=\n' | head -c "$2"; }

if [[ ! -f .env ]]; then
    cat > .env <<EOF
# --- fill these in -------------------------------------------------------------
# Public host name, pointing at this machine (ports 80 and 443 open).
WAFER_DOMAIN=
# For the Let's Encrypt certificate.
ACME_EMAIL=
# The first sign-in administrator (Rauthy admin UI at https://\$WAFER_DOMAIN/auth/v1/admin).
ADMIN_EMAIL=
# The AI assistant and agent: an OpenRouter key, or ANTHROPIC_API_KEY instead.
OPENROUTER_API_KEY=
# Per-person AI budget per day, US dollars (0 = no limit).
WAFER_AI_DAILY_USD=3

# --- generated by setup.sh: keep secret, don't change after first start -----------
POSTGRES_PASSWORD=$(rand 48 40)
RAUTHY_ADMIN_PASSWORD=$(rand 32 24)
RAUTHY_SECRET_RAFT=$(rand 48 40)
RAUTHY_SECRET_API=$(rand 48 40)
RAUTHY_ENC_KEY_ID=k$(date -u +%Y%m%d)
RAUTHY_ENC_KEY=$(head -c 32 /dev/urandom | base64)

# --- host paths and limits ----------------------------------------------------------
WAFER_DATA_DIR=/srv/wafersmith/data
WAFER_BACKUP_DIR=/srv/wafersmith/backups
BACKUP_KEEP_DAYS=14
WAFER_LIBRELANE_IMAGE=ghcr.io/librelane/librelane:3.0.16
WAFER_JOB_WORKERS=2
WAFER_JOB_CPUS=4
WAFER_JOB_MEMORY=8g
WAFER_JOB_TIMEOUT_MIN=120
WAFER_JOB_RETENTION_DAYS=30
DOCKER_GID=$(getent group docker | cut -d: -f3)
EOF
    chmod 600 .env
    echo "Created .env: fill in WAFER_DOMAIN, ACME_EMAIL, ADMIN_EMAIL and OPENROUTER_API_KEY, then run setup.sh again."
    exit 0
fi

set -a
# shellcheck disable=SC1091
source .env
set +a
for v in WAFER_DOMAIN ACME_EMAIL ADMIN_EMAIL; do
    [[ -n "${!v:-}" ]] || { echo "set $v in .env first" >&2; exit 1; }
done
[[ -n "${OPENROUTER_API_KEY:-}${ANTHROPIC_API_KEY:-}" ]] || echo "note: no AI key in .env; the assistant and agent stay off"

# Passkeys need the host alone, and the origin with its port (443 unless WAFER_DOMAIN names one).
HOST="${WAFER_DOMAIN%%:*}"
if [[ "$WAFER_DOMAIN" == *:* ]]; then ORIGIN_PORT="https://$WAFER_DOMAIN"; else ORIGIN_PORT="https://$WAFER_DOMAIN:443"; fi

# Sign-in: production Rauthy config and the web app's OIDC client, for this domain.
# (On a re-run the folder belongs to Rauthy's user: take it back to rewrite it.)
if [[ $EUID -ne 0 && -d rauthy ]]; then
    docker run --rm -v "$PWD/rauthy:/r" alpine:3 chown -R "$(id -u):$(id -g)" /r
fi
mkdir -p rauthy/bootstrap
umask 077
cat > rauthy/config.toml <<EOF
# Generated by setup.sh for $WAFER_DOMAIN. Holds secrets: keep it readable by root only.
[access]
cookie_mode = 'host'
token_revoke_on_logout = true

[bootstrap]
admin_email = '$ADMIN_EMAIL'
bootstrap_dir = 'bootstrap'

[cluster]
node_id = 1
nodes = ["1 localhost:8100 localhost:8200"]
secret_raft = "$RAUTHY_SECRET_RAFT"
secret_api = "$RAUTHY_SECRET_API"
# Nightly consistent snapshots in /app/data/backups (picked up by backup.sh).
backup_keep_for_local = '14d'

[database]
hiqlite = true

[email]
rauthy_admin_email = '$ADMIN_EMAIL'

[encryption]
keys = ['$RAUTHY_ENC_KEY_ID/$RAUTHY_ENC_KEY']
key_active = '$RAUTHY_ENC_KEY_ID'

[mfa]
admin_force_mfa = true

[server]
port_http = 8080
scheme = 'http'
pub_url = '$WAFER_DOMAIN'
proxy_mode = true
trusted_proxies = ['172.16.0.0/12', '10.0.0.0/8', '192.168.0.0/16']
http_workers = 2
metrics_enable = false
swagger_ui_enable = false

[user_registration]
enable = false

[webauthn]
rp_id = '$HOST'
rp_origin = '$ORIGIN_PORT'
rp_name = 'Wafersmith'
EOF
cat > rauthy/bootstrap/clients.json <<EOF
[
    {
        "id": "wafersmith-web",
        "name": "Wafersmith",
        "secret": null,
        "redirect_uris": ["https://$WAFER_DOMAIN/auth/callback"],
        "post_logout_redirect_uris": ["https://$WAFER_DOMAIN/"],
        "allowed_origins": ["https://$WAFER_DOMAIN"],
        "enabled": true,
        "flows_enabled": ["authorization_code", "refresh_token"],
        "access_token_alg": "RS256",
        "id_token_alg": "RS256",
        "auth_code_lifetime": 60,
        "access_token_lifetime": 1800,
        "scopes": ["openid", "profile", "email"],
        "default_scopes": ["openid", "profile", "email"],
        "challenges": ["S256"],
        "force_mfa": false
    }
]
EOF
umask 022
# Rauthy runs as uid 10001 in its image and must read its config (and nobody else may).
if [[ $EUID -eq 0 ]]; then
    chown -R 10001:10001 rauthy
else
    docker run --rm -v "$PWD/rauthy:/r" alpine:3 chown -R 10001:10001 /r
fi

# Data and backups, owned by the API's user (job containers run as that user too).
mkdir -p "$WAFER_DATA_DIR" "$WAFER_BACKUP_DIR"
if [[ $EUID -eq 0 ]]; then
    chown 10001:10001 "$WAFER_DATA_DIR"
    chmod 700 "$WAFER_DATA_DIR" "$WAFER_BACKUP_DIR"
else
    docker run --rm -v "$WAFER_DATA_DIR:/d" alpine:3 chown 10001:10001 /d
    docker run --rm -v "$WAFER_DATA_DIR:/d" -v "$WAFER_BACKUP_DIR:/b" alpine:3 chmod 700 /d /b
fi

# The flow toolchain and the PDK.
WAFER_LIBRELANE_IMAGE="$WAFER_LIBRELANE_IMAGE" WAFER_PDK_VOLUME=wafersmith_pdk "$ROOT/scripts/fetch-pdk.sh"

echo
echo "Ready. Start with:  docker compose up -d --build"
echo "Then sign in at https://$WAFER_DOMAIN/auth/v1/admin as $ADMIN_EMAIL"
echo "(initial password: RAUTHY_ADMIN_PASSWORD in .env; you'll be asked to set up MFA)."
