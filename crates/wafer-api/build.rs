//! Embeds the starter designs: every design-eval task with a `starter` entry in its `task.json`
//! (`evals/design/tasks/<id>/`). Only the description, spec and reference design are built in; the
//! hidden testbenches stay out.

use std::path::Path;

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../evals/design/tasks");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut ids: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e} (the starter designs are built into the API)", dir.display()))
        .filter_map(|e| e.ok())
        .filter(|e| e.path().join("task.json").exists())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .collect();
    ids.sort();
    let mut out = String::from(
        "/// `(id, task.json, spec.json, ref.v)` of every starter design, generated by build.rs.\n\
         pub static RAW: &[(&str, &str, &str, &str)] = &[\n",
    );
    for id in &ids {
        let d = dir.join(id);
        for f in ["task.json", "spec.json", "ref.v"] {
            println!("cargo:rerun-if-changed={}", d.join(f).display());
        }
        let task = std::fs::read_to_string(d.join("task.json")).expect("task.json");
        if !task.contains("\"starter\"") {
            continue;
        }
        let p = |f: &str| format!("{:?}", d.join(f).canonicalize().expect("starter file").display().to_string());
        out.push_str(&format!(
            "    ({id:?}, include_str!({}), include_str!({}), include_str!({})),\n",
            p("task.json"),
            p("spec.json"),
            p("ref.v")
        ));
    }
    out.push_str("];\n");
    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("starters.rs");
    std::fs::write(dest, out).expect("write starters.rs");
}
