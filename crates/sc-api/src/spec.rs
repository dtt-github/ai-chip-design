//! Intent-first design: `spec.json` describes what a design should do in
//! plain language (its connections, settings and decisions), plus worked
//! **examples** that are the tests. Each example is a short table of steps
//! (set an input, wait some clock cycles, expect an output) and is compiled,
//! deterministically, into a self-checking testbench `tb/examples/tb_ex_<id>.v`.
//! Those testbenches are ordinary project files, so the simulation gate, the
//! browser simulator and gate-level simulation all run them: a change (by a
//! person or the agent) is only accepted when every example passes.
//!
//! Step semantics, all on the falling clock edge so inputs settle before the
//! design samples them on the rising edge:
//! - `set`: drive an input now (no time passes);
//! - `wait`: let `cycles` clock cycles pass;
//! - `wait_until`: wait until `signal` equals `value`, failing after `cycles`;
//! - `expect`: `signal` must equal `value` now;
//! - `expect_for`: `signal` must equal `value` for the next `cycles` cycles
//!   (time advances past them).
//!
//! Before the steps, inputs start at 0 and reset (if any) is held for two cycles.

use std::collections::{BTreeMap, BTreeSet};

use serde::{Deserialize, Serialize};

pub const SPEC_FILE: &str = "spec.json";
pub const EXAMPLES_DIR: &str = "tb/examples";
/// First line of every generated testbench; only files carrying it are replaced or removed.
const GENERATED: &str = "// Generated by SiliconCommons from spec.json";
const MAX_CYCLES: u32 = 1_000_000;
const RESET_CYCLES: u32 = 2;

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Spec {
    #[serde(default = "one")]
    pub version: u32,
    /// The request in the user's own words.
    #[serde(default)]
    pub intent: String,
    /// Top module the examples drive.
    pub top: String,
    pub clock: Option<Clock>,
    pub reset: Option<Reset>,
    #[serde(default)]
    pub ports: Vec<Port>,
    /// Settings: design parameters with a plain-language meaning.
    #[serde(default)]
    pub params: Vec<Param>,
    /// Questions that were answered, kept as part of the spec.
    #[serde(default)]
    pub decisions: Vec<Decision>,
    /// Open questions from the assistant, waiting for an answer.
    #[serde(default)]
    pub questions: Vec<Question>,
    #[serde(default)]
    pub examples: Vec<Example>,
}

fn one() -> u32 {
    1
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Clock {
    pub port: String,
    pub mhz: f64,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Reset {
    pub port: String,
    /// `true`: 0 resets (e.g. `rst_n`).
    pub active_low: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Port {
    pub name: String,
    /// `in` or `out`.
    pub dir: String,
    pub width: u32,
    #[serde(default)]
    pub meaning: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Param {
    pub name: String,
    pub value: String,
    #[serde(default)]
    pub meaning: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Decision {
    pub question: String,
    pub answer: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Question {
    pub question: String,
    #[serde(default)]
    pub options: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Example {
    /// `[a-z0-9_]`, unique; names the testbench `tb_ex_<id>`.
    pub id: String,
    pub title: String,
    #[serde(default)]
    pub given: String,
    #[serde(default)]
    pub expect: String,
    /// Parameter overrides for this example (e.g. PARITY = 1).
    #[serde(default)]
    pub params: Vec<ParamValue>,
    pub steps: Vec<Step>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ParamValue {
    pub name: String,
    pub value: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Step {
    pub op: String,
    #[serde(default)]
    pub signal: String,
    #[serde(default)]
    pub value: String,
    #[serde(default)]
    pub cycles: u32,
    /// Plain-language note shown next to the step ("start bit").
    #[serde(default)]
    pub note: String,
}

pub fn tb_name(id: &str) -> String {
    format!("tb_ex_{id}")
}

pub fn tb_path(id: &str) -> String {
    format!("{EXAMPLES_DIR}/{}.v", tb_name(id))
}

/// Whether `content` is a testbench this module generated (safe to replace or delete).
pub fn is_generated(content: &str) -> bool {
    content.starts_with(GENERATED)
}

fn ident(s: &str) -> bool {
    let mut c = s.chars();
    c.next().is_some_and(|f| f.is_ascii_alphabetic() || f == '_')
        && s.len() <= 64
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// A value as written by a person: `85`, `0x55`, `0b0101`, `8'h55`, `'b1`. Returns the number.
pub fn parse_value(s: &str) -> Option<u64> {
    let s = s.trim().replace('_', "");
    let lower = s.to_ascii_lowercase();
    if let Some(h) = lower.strip_prefix("0x") {
        return u64::from_str_radix(h, 16).ok();
    }
    if let Some(b) = lower.strip_prefix("0b") {
        return u64::from_str_radix(b, 2).ok();
    }
    if let Some((_, rest)) = lower.split_once('\'') {
        let rest = rest.trim_start_matches('s');
        let (radix, digits) = match rest.chars().next()? {
            'h' => (16, &rest[1..]),
            'b' => (2, &rest[1..]),
            'o' => (8, &rest[1..]),
            'd' => (10, &rest[1..]),
            _ => return None,
        };
        return u64::from_str_radix(digits, radix).ok();
    }
    lower.parse().ok()
}

fn fits(v: u64, width: u32) -> bool {
    width >= 64 || v < (1u64 << width)
}

impl Spec {
    /// Every problem, in plain language; empty when the spec can be compiled.
    pub fn validate(&self) -> Vec<String> {
        let mut errs = Vec::new();
        if !ident(&self.top) {
            errs.push(format!("the top module name '{}' is not a valid Verilog name", self.top));
        }
        let mut names = BTreeSet::new();
        for p in &self.ports {
            if !ident(&p.name) {
                errs.push(format!("'{}' is not a valid connection name", p.name));
            }
            if !names.insert(p.name.as_str()) {
                errs.push(format!("connection '{}' is listed twice", p.name));
            }
            if p.dir != "in" && p.dir != "out" {
                errs.push(format!("connection '{}' must be 'in' or 'out'", p.name));
            }
            if !(1..=64).contains(&p.width) {
                errs.push(format!("connection '{}' must be 1 to 64 bits wide", p.name));
            }
        }
        let input = |n: &str| self.ports.iter().any(|p| p.name == n && p.dir == "in" && p.width == 1);
        if let Some(c) = &self.clock {
            if !input(&c.port) {
                errs.push(format!("the clock '{}' must be a 1-bit input connection", c.port));
            }
            if !(c.mhz > 0.0 && c.mhz <= 2000.0) {
                errs.push("the clock must be between 0 and 2000 MHz".into());
            }
        }
        if let Some(r) = &self.reset
            && !input(&r.port)
        {
            errs.push(format!("the reset '{}' must be a 1-bit input connection", r.port));
        }
        for p in &self.params {
            if !ident(&p.name) {
                errs.push(format!("'{}' is not a valid setting name", p.name));
            }
        }
        let mut ids = BTreeSet::new();
        for e in &self.examples {
            let at = format!("example '{}'", e.title);
            if e.id.is_empty()
                || e.id.len() > 40
                || !e.id.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            {
                errs.push(format!("{at}: id '{}' must be lowercase letters, digits and _", e.id));
            }
            if !ids.insert(e.id.as_str()) {
                errs.push(format!("{at}: id '{}' is used twice", e.id));
            }
            if e.steps.is_empty() {
                errs.push(format!("{at} has no steps"));
            }
            for p in &e.params {
                if !ident(&p.name) || parse_value(&p.value).is_none() {
                    errs.push(format!("{at}: setting {} = {} is not a name and a number", p.name, p.value));
                }
            }
            for (i, s) in e.steps.iter().enumerate() {
                let n = i + 1;
                let port = self.ports.iter().find(|p| p.name == s.signal);
                let needs_signal = s.op != "wait";
                if needs_signal {
                    match port {
                        None => errs.push(format!("{at}, step {n}: '{}' is not one of the connections", s.signal)),
                        Some(p) => {
                            if s.op == "set" && p.dir != "in" {
                                errs.push(format!(
                                    "{at}, step {n}: can only set inputs, and '{}' is an output",
                                    p.name
                                ));
                            }
                            if self.clock.as_ref().is_some_and(|c| c.port == p.name) {
                                errs.push(format!("{at}, step {n}: the clock runs by itself; use a wait step"));
                            }
                            match parse_value(&s.value) {
                                None => errs.push(format!("{at}, step {n}: '{}' is not a number", s.value)),
                                Some(v) if !fits(v, p.width) => {
                                    errs.push(format!("{at}, step {n}: {} doesn't fit in {} bit(s)", s.value, p.width))
                                }
                                _ => {}
                            }
                        }
                    }
                }
                match s.op.as_str() {
                    "set" | "expect" => {}
                    "wait" | "wait_until" | "expect_for" => {
                        if !(1..=MAX_CYCLES).contains(&s.cycles) {
                            errs.push(format!("{at}, step {n}: cycles must be 1 to {MAX_CYCLES}"));
                        }
                    }
                    other => errs.push(format!("{at}, step {n}: unknown step '{other}'")),
                }
            }
        }
        errs
    }

    fn port(&self, name: &str) -> &Port {
        self.ports.iter().find(|p| p.name == name).expect("validated")
    }

    fn lit(&self, signal: &str, value: &str) -> String {
        let w = self.port(signal).width;
        format!("{w}'h{:x}", parse_value(value).expect("validated"))
    }

    /// The testbench for one example. Call only on a spec that [`validate`](Self::validate)s.
    pub fn testbench(&self, e: &Example) -> String {
        let mut o = String::new();
        let clean = |s: &str| s.replace(['\n', '\r'], " ");
        o.push_str(&format!("{GENERATED}, example \"{}\": {}\n", e.id, clean(&e.title)));
        o.push_str("// Do not edit: change the example instead and this file is regenerated.\n");
        if !e.given.is_empty() {
            o.push_str(&format!("// Given: {}\n", clean(&e.given)));
        }
        if !e.expect.is_empty() {
            o.push_str(&format!("// Expect: {}\n", clean(&e.expect)));
        }
        // Whole picoseconds per half period, so any clock frequency works.
        let half_ps = self.clock.as_ref().map(|c| (500_000.0 / c.mhz).round().max(1.0) as u64).unwrap_or(5_000);
        o.push_str("`timescale 1ps/1ps\n");
        o.push_str(&format!("module {};\n", tb_name(&e.id)));
        let reset_on = self.reset.as_ref().map(|r| if r.active_low { "1'b0" } else { "1'b1" });
        for p in &self.ports {
            let range = if p.width > 1 { format!("[{}:0] ", p.width - 1) } else { String::new() };
            if p.dir == "in" {
                let init = match &self.reset {
                    Some(r) if r.port == p.name => reset_on.unwrap().to_string(),
                    _ => format!("{}'h0", p.width),
                };
                o.push_str(&format!("    reg  {range}{} = {init};\n", p.name));
            } else {
                o.push_str(&format!("    wire {range}{};\n", p.name));
            }
        }
        o.push_str("    integer errors = 0;\n    integer k;\n    integer bad;\n\n");
        let params = if e.params.is_empty() {
            String::new()
        } else {
            let list: Vec<String> = e
                .params
                .iter()
                .map(|p| format!(".{}({})", p.name, parse_value(&p.value).expect("validated")))
                .collect();
            format!(" #({})", list.join(", "))
        };
        let conns: Vec<String> = self.ports.iter().map(|p| format!(".{0}({0})", p.name)).collect();
        o.push_str(&format!("    {}{params} dut ({});\n\n", self.top, conns.join(", ")));
        let tick = match &self.clock {
            Some(c) => {
                o.push_str(&format!("    always #{half_ps} {0} = ~{0};\n\n", c.port));
                format!("@(negedge {})", c.port)
            }
            None => format!("#{}", half_ps * 2),
        };

        o.push_str("    initial begin\n");
        if let Some(r) = &self.reset {
            let off = if r.active_low { "1'b1" } else { "1'b0" };
            o.push_str(&format!("        // Hold reset for {RESET_CYCLES} cycles.\n"));
            o.push_str(&format!("        repeat ({RESET_CYCLES}) {tick};\n        {} = {off};\n", r.port));
        } else {
            o.push_str(&format!("        {tick};\n"));
        }
        for (i, s) in e.steps.iter().enumerate() {
            let n = i + 1;
            let note = if s.note.is_empty() { String::new() } else { format!(" ({})", clean(&s.note)) };
            let fail = |what: &str| format!("$display(\"FAIL: step {n}: {what}, got 0x%0h\", {});", s.signal);
            match s.op.as_str() {
                "set" => {
                    o.push_str(&format!("        // {n}. set {} = {}{note}\n", s.signal, s.value));
                    o.push_str(&format!("        {} = {};\n", s.signal, self.lit(&s.signal, &s.value)));
                }
                "wait" => {
                    o.push_str(&format!("        // {n}. wait {} cycle(s){note}\n", s.cycles));
                    o.push_str(&format!("        repeat ({}) {tick};\n", s.cycles));
                }
                "wait_until" => {
                    let v = self.lit(&s.signal, &s.value);
                    o.push_str(&format!(
                        "        // {n}. wait until {} = {}, at most {} cycle(s){note}\n",
                        s.signal, s.value, s.cycles
                    ));
                    o.push_str(&format!(
                        "        k = 0;\n        while ({sig} !== {v} && k < {c}) begin {tick}; k = k + 1; end\n        if ({sig} !== {v}) begin {msg} errors = errors + 1; end\n",
                        sig = s.signal,
                        c = s.cycles,
                        msg = fail(&format!("{} never became {} within {} cycle(s)", s.signal, s.value, s.cycles)),
                    ));
                }
                "expect" => {
                    let v = self.lit(&s.signal, &s.value);
                    o.push_str(&format!("        // {n}. expect {} = {}{note}\n", s.signal, s.value));
                    o.push_str(&format!(
                        "        if ({sig} !== {v}) begin {msg} errors = errors + 1; end\n",
                        sig = s.signal,
                        msg = fail(&format!("expected {} = {}", s.signal, s.value)),
                    ));
                }
                "expect_for" => {
                    let v = self.lit(&s.signal, &s.value);
                    o.push_str(&format!(
                        "        // {n}. expect {} = {} for {} cycle(s){note}\n",
                        s.signal, s.value, s.cycles
                    ));
                    o.push_str(&format!(
                        "        bad = 0;\n        for (k = 0; k < {c}; k = k + 1) begin\n            if ({sig} !== {v} && bad == 0) begin $display(\"FAIL: step {n}: expected {sig} = {val} for {c} cycle(s), but at cycle %0d got 0x%0h\", k, {sig}); bad = 1; errors = errors + 1; end\n            {tick};\n        end\n",
                        sig = s.signal,
                        c = s.cycles,
                        val = s.value.replace('"', ""),
                    ));
                }
                _ => unreachable!("validated"),
            }
        }
        o.push_str(&format!(
            "        if (errors == 0) $display(\"PASS: example {id}\");\n        else $display(\"FAIL: example {id}: %0d check(s) failed\", errors);\n        $finish;\n    end\nendmodule\n",
            id = e.id
        ));
        o
    }

    /// Generated testbenches by path.
    pub fn testbenches(&self) -> BTreeMap<String, String> {
        self.examples.iter().map(|e| (tb_path(&e.id), self.testbench(e))).collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const DUT: &str =
        "module pulse(input wire clk, input wire rst_n, input wire go, output reg [3:0] n, output reg busy);
  always @(posedge clk or negedge rst_n)
    if (!rst_n) begin n <= 0; busy <= 0; end
    else if (go && !busy) begin busy <= 1; n <= 0; end
    else if (busy) begin n <= n + 1; if (n == 4'd4) busy <= 0; end
endmodule
";

    fn step(op: &str, signal: &str, value: &str, cycles: u32) -> Step {
        Step { op: op.into(), signal: signal.into(), value: value.into(), cycles, note: String::new() }
    }

    fn spec(steps: Vec<Step>) -> Spec {
        let port =
            |name: &str, dir: &str, width| Port { name: name.into(), dir: dir.into(), width, meaning: String::new() };
        Spec {
            version: 1,
            top: "pulse".into(),
            clock: Some(Clock { port: "clk".into(), mhz: 50.0 }),
            reset: Some(Reset { port: "rst_n".into(), active_low: true }),
            ports: vec![
                port("clk", "in", 1),
                port("rst_n", "in", 1),
                port("go", "in", 1),
                port("n", "out", 4),
                port("busy", "out", 1),
            ],
            examples: vec![Example {
                id: "busy_five".into(),
                title: "busy lasts five cycles".into(),
                given: String::new(),
                expect: String::new(),
                params: vec![],
                steps,
            }],
            ..Default::default()
        }
    }

    fn run(s: &Spec) -> crate::gate::GateReport {
        assert_eq!(s.validate(), Vec::<String>::new());
        let mut files: BTreeMap<String, String> = s.testbenches();
        files.insert("src/pulse.v".into(), DUT.into());
        crate::gate::run(&files)
    }

    #[test]
    fn examples_become_passing_and_failing_testbenches() {
        let good = spec(vec![
            step("expect", "busy", "0", 0),
            step("set", "go", "1", 0),
            step("wait", "", "", 1),
            step("set", "go", "0", 0),
            step("expect_for", "busy", "1", 5),
            step("expect", "busy", "0", 0),
            step("expect", "n", "0x5", 0),
        ]);
        let r = run(&good);
        assert!(r.passed, "{r:#?}\n{}", good.testbench(&good.examples[0]));
        assert_eq!(r.runs[0].top, "tb_ex_busy_five");

        let wrong = spec(vec![step("set", "go", "1", 0), step("wait", "", "", 1), step("expect_for", "busy", "1", 6)]);
        let r = run(&wrong);
        assert!(!r.passed);
        assert!(
            r.runs[0].log.iter().any(|l| l.contains("FAIL: step 3") && l.contains("at cycle 5")),
            "{:?}",
            r.runs[0].log
        );

        let timeout = spec(vec![step("wait_until", "busy", "1", 3)]);
        let r = run(&timeout);
        assert!(r.runs[0].log.iter().any(|l| l.contains("never became 1 within 3")), "{:?}", r.runs[0].log);
    }

    #[test]
    fn validation_speaks_plainly() {
        let s = spec(vec![
            step("set", "busy", "1", 0),
            step("expect", "nope", "1", 0),
            step("set", "go", "2", 0),
            step("wait", "", "", 0),
            step("jump", "go", "1", 0),
        ]);
        let errs = s.validate().join("\n");
        assert!(errs.contains("can only set inputs"), "{errs}");
        assert!(errs.contains("'nope' is not one of the connections"), "{errs}");
        assert!(errs.contains("doesn't fit in 1 bit"), "{errs}");
        assert!(errs.contains("cycles must be"), "{errs}");
        assert!(errs.contains("unknown step 'jump'"), "{errs}");
    }

    #[test]
    fn values_and_generated_marker() {
        assert_eq!(parse_value("85"), Some(85));
        assert_eq!(parse_value("0x55"), Some(0x55));
        assert_eq!(parse_value("0b1010_1010"), Some(0xaa));
        assert_eq!(parse_value("8'hA7"), Some(0xa7));
        assert_eq!(parse_value("'b1"), Some(1));
        assert_eq!(parse_value("x"), None);
        let s = spec(vec![step("expect", "busy", "0", 0)]);
        let tb = s.testbench(&s.examples[0]);
        assert!(is_generated(&tb));
        assert!(!is_generated("module tb; endmodule"));
        // Odd clock frequencies still get a whole-picosecond half period.
        let mut odd = s.clone();
        odd.clock.as_mut().unwrap().mhz = 33.0;
        assert!(odd.testbench(&odd.examples[0]).contains("always #15152 clk"));
    }
}
