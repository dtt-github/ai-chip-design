//! The Blocks view: a chip built from blocks. `blocks.json` lists the blocks (modules of this
//! project, imported IP, or adapters from a small built-in library), the chip's pins and the
//! connections between them. Saving checks the connections and generates the top-level Verilog,
//! deterministically, into `src/<top>.v` (and the adapters into `src/sc_adapters.v`), like
//! examples become testbenches.
//!
//! Checks that need no judgement are done here: every end exists, signals flow from an output
//! (or an input pin) to an input (or an output pin), widths match, each input has one driver,
//! and every block input is connected (unconnected ones are tied to 0, with a warning). Ports
//! named like the chip's clock and reset are connected to them automatically. Whether a
//! connection makes sense (a level where a pulse is expected) is for the assistant to review.

use std::collections::{BTreeMap, BTreeSet, HashMap};

use serde::{Deserialize, Serialize};

pub const BLOCKS_FILE: &str = "blocks.json";
pub const ADAPTERS_FILE: &str = "src/sc_adapters.v";
const GENERATED: &str = "// Generated by SiliconCommons from blocks.json";

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct Blocks {
    /// Name of the generated top module (the chip).
    pub top: String,
    /// Chip pins that are the clock and reset; block ports with the same names connect to them.
    #[serde(default)]
    pub clock: Option<String>,
    #[serde(default)]
    pub reset: Option<String>,
    #[serde(default)]
    pub pins: Vec<Pin>,
    #[serde(default)]
    pub blocks: Vec<Block>,
    #[serde(default)]
    pub wires: Vec<Wire>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Pin {
    pub name: String,
    /// `in` or `out`, seen from the chip.
    pub dir: String,
    pub width: u32,
    #[serde(default)]
    pub meaning: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Block {
    /// Instance name.
    pub name: String,
    pub module: String,
    #[serde(default)]
    pub params: BTreeMap<String, String>,
    /// Position on the canvas.
    #[serde(default)]
    pub x: f64,
    #[serde(default)]
    pub y: f64,
}

/// A connection; each end is `pin` or `block.port`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Wire {
    pub from: String,
    pub to: String,
}

/// A module that can be placed as a block.
#[derive(Debug, Clone, Serialize)]
pub struct ModuleInfo {
    pub name: String,
    pub file: String,
    /// `project`, `starter`, `ip:<block>`, or `adapter`.
    pub source: String,
    pub params: BTreeMap<String, i64>,
    pub ports: Vec<PortInfo>,
    pub description: String,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct PortInfo {
    pub name: String,
    /// `in`, `out` or `inout`.
    pub dir: String,
    pub width: u32,
}

/// A problem with one connection or block, in plain words.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct Issue {
    /// `error` (can't be built) or `warning`.
    pub level: String,
    /// The wire index, if it is about a wire.
    pub wire: Option<usize>,
    pub block: Option<String>,
    pub message: String,
}

// ---- the adapter library ------------------------------------------------------------

/// Small adapters for the mismatches the assistant finds most often.
pub const ADAPTERS: &str = r#"// Generated by SiliconCommons from blocks.json: the adapter library. Do not edit.
// SPDX-License-Identifier: Apache-2.0
`default_nettype none

// Turns a level into a one-clock pulse when it goes from 0 to 1.
module sc_rise_pulse (input wire clk, input wire rst_n, input wire level, output wire pulse);
    reg last;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) last <= 1'b0;
        else last <= level;
    assign pulse = level & ~last;
endmodule

// Brings a signal from outside the chip (or another clock) safely into this clock: two flip-flops.
module sc_sync2 (input wire clk, input wire rst_n, input wire d, output wire q);
    reg s1, s2;
    always @(posedge clk or negedge rst_n)
        if (!rst_n) begin s1 <= 1'b0; s2 <= 1'b0; end
        else begin s1 <= d; s2 <= s1; end
    assign q = s2;
endmodule

// Flips every bit (for example an active-low signal into an active-high one).
module sc_invert #(parameter W = 1) (input wire [W-1:0] a, output wire [W-1:0] y);
    assign y = ~a;
endmodule

// Changes a value's width: pads with zeros on the left, or keeps the lowest bits.
module sc_resize #(parameter IN = 8, parameter OUT = 8) (input wire [IN-1:0] a, output wire [OUT-1:0] y);
    localparam MAXW = (IN > OUT) ? IN : OUT;
    wire [MAXW-1:0] wide = {{MAXW{1'b0}}} | a;
    assign y = wide[OUT-1:0];
endmodule
"#;

/// Plain descriptions of the adapters, by module name.
pub fn adapter_description(name: &str) -> Option<&'static str> {
    Some(match name {
        "sc_rise_pulse" => "Turns a level into a one-clock pulse when it goes from 0 to 1",
        "sc_sync2" => "Brings a signal from outside the chip safely into this clock (two flip-flops)",
        "sc_invert" => "Flips every bit, e.g. an active-low signal into an active-high one",
        "sc_resize" => "Changes a value's width: pads with zeros, or keeps the lowest bits",
        _ => return None,
    })
}

/// The adapter library's Verilog.
pub fn adapters_source() -> String {
    ADAPTERS.to_string()
}

// ---- discovery -------------------------------------------------------------------

fn is_hdl(path: &str) -> bool {
    path.rsplit_once('.').is_some_and(|(_, e)| matches!(e, "v" | "sv"))
}

/// Modules that can be placed: the project's (not testbenches, not the generated top), imported
/// IP, and the adapters. Run on a big stack (it parses and elaborates).
pub fn discover(files: &BTreeMap<String, String>, top: Option<&str>) -> (Vec<ModuleInfo>, Vec<String>) {
    let mut problems = Vec::new();
    let mut sources: Vec<(String, String)> = files
        .iter()
        .filter(|(p, c)| is_hdl(p) && !p.starts_with("tb/") && p.as_str() != ADAPTERS_FILE && !c.starts_with(GENERATED))
        .map(|(p, c)| (p.clone(), c.clone()))
        .collect();
    sources.push((ADAPTERS_FILE.into(), adapters_source()));
    let refs: Vec<(&str, &str)> = sources.iter().map(|(p, c)| (p.as_str(), c.as_str())).collect();
    let modules = match sc_sim::parse(&refs) {
        Ok((m, _)) => m,
        Err(e) => {
            problems.push(format!("the design files don't parse, so blocks can't be listed: {e}"));
            return (Vec::new(), problems);
        }
    };
    let mut out = Vec::new();
    for m in &modules {
        if crate::gate::looks_like_tb(&m.name) || Some(m.name.as_str()) == top {
            continue;
        }
        match module_ports(&modules, &m.name, &HashMap::new()) {
            Ok((params, ports)) => {
                let starter = m
                    .file
                    .strip_prefix(&format!("{}/", crate::starters::DIR))
                    .and_then(|_| crate::starters::all().iter().find(|s| s.top == m.name));
                let source = if m.file == ADAPTERS_FILE {
                    "adapter".to_string()
                } else if starter.is_some() {
                    "starter".to_string()
                } else if let Some(rest) = m.file.strip_prefix("ip/") {
                    format!("ip:{}", rest.split('/').next().unwrap_or(""))
                } else {
                    "project".to_string()
                };
                out.push(ModuleInfo {
                    description: starter
                        .map(|s| s.summary.clone())
                        .unwrap_or_else(|| adapter_description(&m.name).unwrap_or("").to_string()),
                    name: m.name.clone(),
                    file: m.file.clone(),
                    source,
                    params,
                    ports,
                })
            }
            Err(e) => problems.push(format!("module {} can't be used as a block: {e}", m.name)),
        }
    }
    out.sort_by(|a, b| {
        (a.source != "project", a.source.clone(), a.name.clone()).cmp(&(
            b.source != "project",
            b.source.clone(),
            b.name.clone(),
        ))
    });
    (out, problems)
}

/// A module's parameters and ports (with widths) for given parameter values.
fn module_ports(
    modules: &[sc_sim::ast::Module],
    name: &str,
    overrides: &HashMap<String, i64>,
) -> Result<(BTreeMap<String, i64>, Vec<PortInfo>), String> {
    let m = modules.iter().find(|m| m.name == name).ok_or_else(|| format!("no module named {name}"))?;
    let d = sc_sim::elab::elaborate_with(modules, name, overrides).map_err(|e| e.to_string())?;
    let mut dirs = HashMap::new();
    for item in &m.items {
        if let sc_sim::ast::Item::Decl(decl) = item
            && let Some(dir) = decl.dir
        {
            for n in &decl.names {
                dirs.insert(n.name.as_str(), dir);
            }
        }
    }
    let ports = m
        .ports
        .iter()
        .map(|p| PortInfo {
            name: p.clone(),
            dir: match dirs.get(p.as_str()) {
                Some(sc_sim::ast::Dir::Input) => "in",
                Some(sc_sim::ast::Dir::Output) => "out",
                _ => "inout",
            }
            .into(),
            width: d.names.get(&format!("{name}.{p}")).map(|&i| d.signals[i].width).unwrap_or(1),
        })
        .collect();
    Ok((d.instances[0].params.clone(), ports))
}

// ---- checking and generation ----------------------------------------------------------

fn ident(s: &str) -> bool {
    let mut c = s.chars();
    c.next().is_some_and(|f| f.is_ascii_alphabetic() || f == '_')
        && s.len() <= 64
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// One end of a wire, resolved.
#[derive(Debug, Clone, PartialEq)]
enum End {
    Pin(String),
    Port { block: String, port: String },
}

fn parse_end(s: &str) -> End {
    match s.split_once('.') {
        Some((b, p)) => End::Port { block: b.into(), port: p.into() },
        None => End::Pin(s.into()),
    }
}

/// The checked design: ports of every block (with its parameters), or the problems.
pub struct Checked {
    pub issues: Vec<Issue>,
    /// Ports per block instance.
    pub ports: BTreeMap<String, Vec<PortInfo>>,
    /// Generated top and whether the adapters are used; `None` when there are errors.
    pub verilog: Option<String>,
    pub uses_adapters: bool,
}

impl Blocks {
    /// Checks everything and, if nothing is wrong, generates the top module. `files` are the
    /// project's files (for the modules); run on a big stack.
    pub fn check(&self, files: &BTreeMap<String, String>) -> Checked {
        let mut issues = Vec::new();
        let err = |issues: &mut Vec<Issue>, wire: Option<usize>, block: Option<&str>, m: String| {
            issues.push(Issue { level: "error".into(), wire, block: block.map(String::from), message: m })
        };
        let warn = |issues: &mut Vec<Issue>, wire: Option<usize>, block: Option<&str>, m: String| {
            issues.push(Issue { level: "warning".into(), wire, block: block.map(String::from), message: m })
        };
        if !ident(&self.top) {
            err(
                &mut issues,
                None,
                None,
                format!("the chip's name '{}' must be a plain name (letters, digits, _)", self.top),
            );
        }
        let mut names = BTreeSet::new();
        for p in &self.pins {
            if !ident(&p.name) || !names.insert(p.name.clone()) {
                err(&mut issues, None, None, format!("pin '{}' needs a unique plain name", p.name));
            }
            if !(1..=64).contains(&p.width) || (p.dir != "in" && p.dir != "out") {
                err(&mut issues, None, None, format!("pin '{}' must be in or out, 1 to 64 bits", p.name));
            }
        }
        for b in &self.blocks {
            if !ident(&b.name) || !names.insert(b.name.clone()) {
                err(
                    &mut issues,
                    None,
                    Some(&b.name),
                    format!("block '{}' needs a unique plain name (not a pin's)", b.name),
                );
            }
        }
        for (role, p) in [("clock", &self.clock), ("reset", &self.reset)] {
            if let Some(p) = p
                && !self.pins.iter().any(|x| &x.name == p && x.dir == "in" && x.width == 1)
            {
                err(&mut issues, None, None, format!("the {role} '{p}' must be a 1-bit input pin"));
            }
        }

        // Modules, with each block's parameters.
        let mut sources: Vec<(String, String)> = files
            .iter()
            .filter(|(p, c)| {
                is_hdl(p) && !p.starts_with("tb/") && p.as_str() != ADAPTERS_FILE && !c.starts_with(GENERATED)
            })
            .map(|(p, c)| (p.clone(), c.clone()))
            .collect();
        sources.push((ADAPTERS_FILE.into(), adapters_source()));
        let refs: Vec<(&str, &str)> = sources.iter().map(|(p, c)| (p.as_str(), c.as_str())).collect();
        let modules = match sc_sim::parse(&refs) {
            Ok((m, _)) => m,
            Err(e) => {
                err(&mut issues, None, None, format!("the design files don't parse: {e}"));
                return Checked { issues, ports: BTreeMap::new(), verilog: None, uses_adapters: false };
            }
        };
        let mut ports: BTreeMap<String, Vec<PortInfo>> = BTreeMap::new();
        for b in &self.blocks {
            if b.module == self.top {
                err(&mut issues, None, Some(&b.name), format!("block '{}' can't be the chip itself", b.name));
                continue;
            }
            let mut ov = HashMap::new();
            for (k, v) in &b.params {
                match crate::spec::parse_value(v).and_then(|v| i64::try_from(v).ok()) {
                    Some(n) => {
                        ov.insert(k.clone(), n);
                    }
                    None => {
                        err(&mut issues, None, Some(&b.name), format!("{}: setting {k} = {v} is not a number", b.name))
                    }
                }
            }
            match module_ports(&modules, &b.module, &ov) {
                Ok((_, p)) => {
                    ports.insert(b.name.clone(), p);
                }
                Err(e) => err(&mut issues, None, Some(&b.name), format!("{}: {e}", b.name)),
            }
        }

        // Each end: direction (as a source or a sink) and width.
        let pin = |n: &str| self.pins.iter().find(|p| p.name == n);
        let port = |b: &str, p: &str| ports.get(b).and_then(|ps| ps.iter().find(|x| x.name == p));
        // (is a driver, width, description)
        let end_info = |e: &End| -> Result<(bool, u32, String), String> {
            match e {
                End::Pin(n) => {
                    pin(n).map(|p| (p.dir == "in", p.width, format!("pin {n}"))).ok_or(format!("there is no pin '{n}'"))
                }
                End::Port { block, port: pn } => {
                    if !self.blocks.iter().any(|b| &b.name == block) {
                        return Err(format!("there is no block '{block}'"));
                    }
                    let p = port(block, pn).ok_or(format!("block {block} has no connection '{pn}'"))?;
                    Ok((p.dir == "out", p.width, format!("{block}.{pn}")))
                }
            }
        };
        let mut driver_of: HashMap<String, usize> = HashMap::new();
        let mut good: Vec<(End, End)> = Vec::new();
        for (i, w) in self.wires.iter().enumerate() {
            let (a, b) = (parse_end(&w.from), parse_end(&w.to));
            let (ia, ib) = match (end_info(&a), end_info(&b)) {
                (Ok(x), Ok(y)) => (x, y),
                (Err(e), _) | (_, Err(e)) => {
                    err(&mut issues, Some(i), None, e);
                    continue;
                }
            };
            // Accept either order; the driver is the end that drives.
            let ((src, (_, ws, ds)), (dst, (_, wd, dd))) = match (ia.0, ib.0) {
                (true, false) => ((a, ia), (b, ib)),
                (false, true) => ((b, ib), (a, ia)),
                (true, true) => {
                    err(
                        &mut issues,
                        Some(i),
                        None,
                        format!("{} and {} both drive a value: connect an output to an input", ia.2, ib.2),
                    );
                    continue;
                }
                (false, false) => {
                    err(
                        &mut issues,
                        Some(i),
                        None,
                        format!("{} and {} both expect a value: one of them must be an output", ia.2, ib.2),
                    );
                    continue;
                }
            };
            if ws != wd {
                err(
                    &mut issues,
                    Some(i),
                    None,
                    format!(
                        "{ds} is {ws} bit{} but {dd} is {wd} bit{}: they must match (a resize adapter can convert)",
                        if ws == 1 { "" } else { "s" },
                        if wd == 1 { "" } else { "s" }
                    ),
                );
                continue;
            }
            let key = format!("{dst:?}");
            if let Some(&j) = driver_of.get(&key) {
                err(
                    &mut issues,
                    Some(i),
                    None,
                    format!("{dd} already gets its value from connection {}; an input can have only one source", j + 1),
                );
                continue;
            }
            driver_of.insert(key, i);
            good.push((src, dst));
        }

        // Clock and reset to same-named ports; other unconnected inputs are tied to 0.
        let mut auto: Vec<(End, End)> = Vec::new();
        for b in &self.blocks {
            for p in ports.get(&b.name).into_iter().flatten().filter(|p| p.dir == "in") {
                let dst = End::Port { block: b.name.clone(), port: p.name.clone() };
                if driver_of.contains_key(&format!("{dst:?}")) {
                    continue;
                }
                let special = [&self.clock, &self.reset].into_iter().flatten().find(|c| *c == &p.name);
                match special {
                    Some(c) => auto.push((End::Pin(c.clone()), dst)),
                    None => warn(
                        &mut issues,
                        None,
                        Some(&b.name),
                        format!("{}.{} isn't connected; it is held at 0", b.name, p.name),
                    ),
                }
            }
        }
        for p in self.pins.iter().filter(|p| p.dir == "out") {
            if !driver_of.contains_key(&format!("{:?}", End::Pin(p.name.clone()))) {
                warn(&mut issues, None, None, format!("output pin {} isn't connected; it is held at 0", p.name));
            }
        }

        let uses_adapters = self.blocks.iter().any(|b| adapter_description(&b.module).is_some());
        let verilog = (!issues.iter().any(|i| i.level == "error")).then(|| self.generate(&ports, &good, &auto));
        Checked { issues, ports, verilog, uses_adapters }
    }

    fn generate(&self, ports: &BTreeMap<String, Vec<PortInfo>>, wires: &[(End, End)], auto: &[(End, End)]) -> String {
        let range = |w: u32| if w > 1 { format!("[{}:0] ", w - 1) } else { String::new() };
        let net = |e: &End| match e {
            End::Pin(n) => n.clone(),
            End::Port { block, port } => format!("{block}__{port}"),
        };
        let mut o = format!("{GENERATED}: the chip's top level. Do not edit: change the blocks instead.\n");
        o.push_str("// SPDX-License-Identifier: Apache-2.0\n`default_nettype none\n\n");
        let pins: Vec<String> = self
            .pins
            .iter()
            .map(|p| {
                format!("    {} wire {}{}", if p.dir == "in" { "input " } else { "output" }, range(p.width), p.name)
            })
            .collect();
        o.push_str(&format!("module {} (\n{}\n);\n", self.top, pins.join(",\n")));
        // A net per block output.
        for b in &self.blocks {
            for p in ports.get(&b.name).into_iter().flatten().filter(|p| p.dir == "out") {
                o.push_str(&format!("    wire {}{}__{};\n", range(p.width), b.name, p.name));
            }
        }
        let source_of = |dst: &End| wires.iter().chain(auto).find(|(_, d)| d == dst).map(|(s, _)| net(s));
        for b in &self.blocks {
            let Some(ps) = ports.get(&b.name) else { continue };
            let params = if b.params.is_empty() {
                String::new()
            } else {
                let list: Vec<String> = b
                    .params
                    .iter()
                    .map(|(k, v)| format!(".{k}({})", crate::spec::parse_value(v).unwrap_or(0)))
                    .collect();
                format!(" #({})", list.join(", "))
            };
            let conns: Vec<String> = ps
                .iter()
                .map(|p| {
                    let here = End::Port { block: b.name.clone(), port: p.name.clone() };
                    let value = match p.dir.as_str() {
                        "out" => net(&here),
                        _ => source_of(&here).unwrap_or_else(|| format!("{}'d0", p.width)),
                    };
                    format!("        .{}({})", p.name, value)
                })
                .collect();
            o.push_str(&format!("\n    {}{params} {} (\n{}\n    );\n", b.module, b.name, conns.join(",\n")));
        }
        o.push('\n');
        for p in self.pins.iter().filter(|p| p.dir == "out") {
            let v = source_of(&End::Pin(p.name.clone())).unwrap_or_else(|| format!("{}'d0", p.width));
            o.push_str(&format!("    assign {} = {v};\n", p.name));
        }
        o.push_str("endmodule\n\n`default_nettype wire\n");
        o
    }
}

/// The generated top's path.
pub fn top_path(top: &str) -> String {
    format!("src/{top}.v")
}

pub fn is_generated(content: &str) -> bool {
    content.starts_with(GENERATED)
}

