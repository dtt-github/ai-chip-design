// Prints the design eval tasks as Markdown, for review: `node evals/design/list-tasks.mjs > evals/design/TASKS.md`.
import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), 'tasks');
const steps = ex => ex.steps.map(s => {
  const v = `${s.signal ?? ''}${s.value != null ? ` = ${s.value}` : ''}`;
  return { set: `set ${v}`, wait: `wait ${s.cycles}`, wait_until: `wait until ${v} (≤ ${s.cycles})`,
           expect: `expect ${v}`, expect_for: `expect ${v} for ${s.cycles}` }[s.op];
}).join(' · ');
const out = ['# Design eval tasks', '',
  'Generated by `node evals/design/list-tasks.mjs` from `tasks/<id>/task.json` and `spec.json`; see [docs/evals.md](../../docs/evals.md).', ''];
for (const id of readdirSync(dir).sort()) {
  const t = JSON.parse(readFileSync(join(dir, id, 'task.json'), 'utf8'));
  const s = JSON.parse(readFileSync(join(dir, id, 'spec.json'), 'utf8'));
  out.push(`## ${id} (${t.kind})`, '', `> ${t.description}`, '');
  if (t.kind === 'vague') {
    out.push('**Open points** (the assistant should ask):', '');
    for (const p of t.open_points) out.push(`- ${p.point} (keywords: ${p.keywords.map(k => `\`${k}\``).join(', ')})`);
    out.push('', '**Reference decisions** (given to the agent; the reference design implements them):', '');
    for (const d of s.decisions) out.push(`- ${d.question} ${d.answer}`);
    out.push('', `**Full behaviour** (the spec's intent): ${s.intent}`, '');
  }
  out.push('**Reference examples:**', '');
  for (const e of s.examples) out.push(`- \`${e.id}\` ${e.title}: ${steps(e)}`);
  if (t.ideal_draft) {
    out.push('', '**Ideal draft** (oracle for the assistant eval: asks, and only examples that hold either way):', '');
    for (const q of t.ideal_draft.questions) out.push(`- Q: ${q.question} (${q.options.join(' / ')})`);
    for (const e of t.ideal_draft.examples) out.push(`- \`${e.id}\` ${e.title}: ${steps(e)}`);
  }
  out.push('');
}
process.stdout.write(out.join('\n'));
